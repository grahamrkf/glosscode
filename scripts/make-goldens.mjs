// Runs the UI's own JavaScript (src/ui/js/, as src/ui/index.html loads it) on every sample program in examples/ and every edge case
// in tests/cases/, and writes what it shows to tests/golden/*.json: the gloss word, unit and description for
// every word, and every problem the checks report. tests/golden/sim/*.json record what the simulation makes of each
// program on each machine: every step (line, Z or X, stops, alarms) and every toolpath segment, numbers rounded to
// 6 places. They are a record of what the UI does: a change to the gloss, the checks, the simulation or the data
// files that changes any of them shows up in the diff. Run from the repo root:
//   node scripts/make-goldens.mjs           write the files
//   node scripts/make-goldens.mjs --check   fail if any file would change (used by CI)
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { loadPage } from "../tests/ui-page.mjs";

const check = process.argv.includes("--check");
const A = loadPage();
mkdirSync("tests/golden/sim", { recursive:true });

// Which machines each program runs on: tests/machines.json.
const SETUP = JSON.parse(readFileSync("tests/machines.json", "utf8"));
const machinesFor = name => {
  const m = SETUP.files[name] ?? SETUP.default;
  return typeof m==="string" ? SETUP.groups[m] : m;
};
// The simulation's result as text: one line per step, segment and other entry, so a change shows as a short diff.
const round = (k, v) => k==="xf" ? undefined : typeof v==="number" ? Math.round(v*1e6)/1e6 + 0 : v;
const one = v => JSON.stringify(v, round);
// A run that loops (a program that calls itself until the step limit) keeps its first 200 steps and segments, the
// counts, and a hash of the whole result.
function simText(r){
  if (!r._full && (r.steps.length > 1000 || r.segs.length > 5000)){
    const hash = createHash("sha256").update(simText({ ...r, steps:r.steps, segs:r.segs, _full:true })).digest("hex").slice(0, 16);
    r = { ...r, steps:r.steps.slice(0, 200), segs:r.segs.slice(0, 200), stepCount:r.steps.length, segCount:r.segs.length, hash };
  }
  delete r._full;
  const parts = Object.entries(r).map(([k, v]) => {
    if (Array.isArray(v) && v.length) return ` ${one(k)}: [\n  ${v.map(one).join(",\n  ")}]`;
    if (v && typeof v==="object" && !Array.isArray(v) && Object.keys(v).length && k!=="alarm") return ` ${one(k)}: {\n  ${Object.entries(v).map(([a, b]) => one(a) + ": " + one(b)).join(",\n  ")}}`;
    return ` ${one(k)}: ${one(v ?? null)}`;
  });
  return "{\n" + parts.join(",\n") + "}";
}
let changed = 0;
const write = (file, out) => {
  if (existsSync(file) && readFileSync(file, "utf8")===out) return;
  changed++;
  if (check) console.error("Out of date:", file); else { writeFileSync(file, out); console.log("Wrote", file); }
};
const sources = ["examples", "tests/cases"].flatMap(dir => readdirSync(dir).sort().map(name => ({ dir, name })));
const stale = Object.keys(SETUP.files).filter(f => !sources.some(s => s.name===f));
if (stale.length) throw new Error(`tests/machines.json lists ${stale.join(", ")}, which isn't in examples/ or tests/cases/`);
for (const [f, m] of Object.entries(SETUP.files)) if (typeof m==="string" && !SETUP.groups[m]) throw new Error(`tests/machines.json: ${f} names no group "${m}"`);
for (const { dir, name } of sources){
  const text = readFileSync(dir + "/" + name, "latin1");
  const lines = text.split(/\r\n|\n|\r/); if (lines.length > 1 && lines[lines.length-1]==="") lines.pop();
  const machines = machinesFor(name);
  // The words are split the way the first machine's control does (Fagor 8060 has its own block syntax)
  A.use(machines[0], "words"); const syntax = A.syntax;
  const doc = []; for (const line of lines) A.splitBlocks(line).blocks.forEach(b => doc.push(A.tokenize(b)));
  const runs = [];
  for (const id of machines) for (const s of id===machines[0] ? ["words", "short"] : ["words"]){
    A.use(id, s); A.doc = doc.map(t => [...t]); A.translateAll();
    const words = A.view.map(cells => cells.map(c => {
      const o = { g:c.g, e:c.e }; if (c.u) o.u = c.u; o.d = c.d2 || c.d || ""; if (c.unk) o.unk = true; if (c.imp) o.imp = true; if (c.cm) o.cm = true; return o; }));
    const problems = A.checkProgram().map(p => ({ li:p.li, id:p.id, sev:p.sev, msg:p.msg }));
    runs.push({ machine:id, style:s, words, problems });
  }
  const out = JSON.stringify({ file:name, about:"Generated by scripts/make-goldens.mjs from the UI. Don't edit by hand.", ...(syntax ? { syntax } : {}), lines:doc, runs }, null, 1) + "\n";
  const file = `tests/golden/${name.replace(/\./g, "_")}.json`;
  write(file, out);
  // The simulation, on each machine; with block delete (/) on too when the program has "/" lines.
  const sims = [];
  const bd = doc.some(t => /^\/\d?$/.test(t[0] || ""));
  for (const id of machines) for (const blockDelete of bd ? [false, true] : [false]){
    A.use(id, "words"); A.doc = doc.map(t => [...t]); A.translateAll(); A.blockDelete = blockDelete;
    sims.push(` {"machine": ${JSON.stringify(id)}${blockDelete ? `, "blockDelete": true` : ""}, "result": ${simText(A.interpret())}}`);
    A.blockDelete = false;
  }
  write(`tests/golden/sim/${name.replace(/\./g, "_")}.json`, `{"file": ${JSON.stringify(name)}, "about": "Generated by scripts/make-goldens.mjs from the UI. Don't edit by hand.",\n"runs": [\n${sims.join(",\n")}]}\n`);
}
if (check && changed){ console.error("Run: node scripts/make-goldens.mjs"); process.exit(1); }
if (!changed) console.log("Goldens up to date");
